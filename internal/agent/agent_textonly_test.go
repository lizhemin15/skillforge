package agent

import "testing"

// 守 agent.ExplicitTextOnly —— 「用户明说只看正文」的确定性判据。
//
// 为什么这把尺子两侧都得有牙：
//   - 漏判（明说了只看正文却判 false）→ chat.go 的出文件纠偏闸门把这一轮抢去生成 .docx，
//     用户拿到文件卡片、正文只有一句「已为您生成《…docx》」。线上真踩到（94 字正文）。
//   - 误判（要 Word 的人被判 true）→ 闸门整个失效，用户要 Word 又只拿到一屏文字 ——
//     反向故障，和修复前一样坏。所以**反向语料是主料，不是点缀**。
func TestExplicitTextOnly(t *testing.T) {
	yes := []struct{ name, msg string }{
		{"线上原话（通知+直接输出正文）",
			"写一份关于开展数据治理专项工作的通知。背景与核心素材：已建成数据中台，覆盖 12 个业务域。正文不少于 600 字，直接输出正文。"},
		{"只要正文", "帮我写一份通知，只要正文就行"},
		{"不要生成文件", "写个通报，不要生成文件"},
		{"不用做 Word", "这段材料整理一下，不用做 Word"},
		{"别出文件", "写份总结，别出文件"},
		{"只要文字", "只要文字，别给我下载链接"},
		{"不要 docx", "把它写成一段文字，不要 docx"},
		{"断词（中间带空格/全角空格）", "直接 输出 正文"},
		{"英文 no file", "summarize it, no file please"},
	}
	for _, c := range yes {
		if !ExplicitTextOnly(c.msg) {
			t.Errorf("[%s] 明说了只看正文却判 false —— 这一轮会被纠偏闸门抢去出文件（线上真故障形态）：%q",
				c.name, c.msg)
		}
	}

	no := []struct{ name, msg string }{
		{"题材词不算（只说通知）", "写一份关于开展数据治理专项工作的通知，不少于 600 字"},
		{"要 Word", "把下面内容生成一份 Word 通知文档"},
		{"要文件", "帮我出一份文件的正式版"},
		{"要下载", "生成一个 docx 给我下载"},
		{"填模板", "用采购验收单模板填一下这批数据"},
		{"闲聊", "今天天气怎么样"},
		{"空", ""},
	}
	for _, c := range no {
		if ExplicitTextOnly(c.msg) {
			t.Errorf("[%s] 没明说只看正文却判 true —— 要文件的用户会被拦下，闸门等于关掉（反向故障）：%q",
				c.name, c.msg)
		}
	}
}
